from pathlib import Path
from itertools import product

OUT = Path(__file__).parent
COINS = {
    "coin1": 1,
    "coin2": 2,
    "coin5": 5,
    "coin10": 10,
}
INPUTS = list(COINS)
OUTPUTS = [
    "vend",
    "bal1", "bal2", "bal4", "bal8",
    "change1", "change2", "change4", "change8",
]

def bits(value, width=4):
    return format(value, f"0{width}b")

def binary4(value):
    return " ".join(bits(value, 4))

def output_bits(balance=0, vend=0, change=0):
    values = [
        vend,
        (balance >> 0) & 1,
        (balance >> 1) & 1,
        (balance >> 2) & 1,
        (balance >> 3) & 1,
        (change >> 0) & 1,
        (change >> 1) & 1,
        (change >> 2) & 1,
        (change >> 3) & 1,
    ]
    return " ".join(map(str, values))

# Balance states: B0 through B9.
# Dispense states: D0 through D9, where the suffix is change in rupees.
states = [f"B{i}" for i in range(10)] + [f"D{i}" for i in range(10)]
patterns = list(product([0, 1], repeat=4))

lines = [
    "# Advanced ₹10 vending machine generated by generate_fsm.py",
    "# Input bit order: coin1 coin2 coin5 coin10",
    "# Balance is binary encoded by bal1, bal2, bal4, bal8.",
    "# change1, change2, change4, change8 encode change when vend=1.",
    "inputs: " + " ".join(INPUTS),
    "outputs: " + " ".join(OUTPUTS),
    "reset: B0",
    "",
    "# current | coin1coin2coin5coin10 | next | outputs",
]

for balance in range(10):
    state = f"B{balance}"

    for pattern in patterns:
        active = [name for name, bit in zip(INPUTS, pattern) if bit]
        input_string = "".join(map(str, pattern))

        # Accept only zero coins or exactly one denomination per event.
        if len(active) == 0:
            next_state = state
        elif len(active) == 1:
            amount = COINS[active[0]]
            total = balance + amount

            if total < 10:
                next_state = f"B{total}"
            else:
                next_state = f"D{total - 10}"
        else:
            # Invalid multi-coin combination: preserve the current balance.
            next_state = state

        # Outputs represent the currently stored balance. Dispensing begins
        # after the clock edge enters a D-state.
        outs = output_bits(balance=balance)
        lines.append(
            f"{state} | {input_string} | {next_state} | {outs}"
        )

for change in range(10):
    state = f"D{change}"

    for pattern in patterns:
        input_string = "".join(map(str, pattern))
        # The D-state displays vend/change for one clock cycle, then returns
        # to B0. Inputs during this cycle are ignored.
        outs = output_bits(balance=0, vend=1, change=change)
        lines.append(f"{state} | {input_string} | B0 | {outs}")

net_path = OUT / "vending_machine_advanced.net"
net_path.write_text("\n".join(lines) + "\n")

print(f"Generated: {net_path}")
print(f"States: {len(states)}")
print(f"Transition rows: {len(lines) - 11}")
print(f"Inputs: {', '.join(INPUTS)}")
print(f"Outputs: {', '.join(OUTPUTS)}")
